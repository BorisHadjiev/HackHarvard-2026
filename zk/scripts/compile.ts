// Compile the Noir circuit and write the artifact + verification key into zk/artifacts/ as a
// TypeScript module, so both Next.js apps can bundle it without reading files at runtime.
// Run after changing zk/circuit/src/main.nr:  npm run compile -w zk
import { mkdirSync, writeFileSync } from "node:fs";
import { compile_program, createFileManager } from "@noir-lang/noir_wasm";
import { Barretenberg, UltraHonkBackend } from "@aztec/bb.js";

const circuitDir = new URL("../circuit", import.meta.url).pathname;
const outDir = new URL("../artifacts", import.meta.url).pathname;
mkdirSync(outDir, { recursive: true });

const { program } = await compile_program(createFileManager(circuitDir));
const api = await Barretenberg.new({ threads: 4 });
const vk = await new UltraHonkBackend(program.bytecode, api).getVerificationKey();
await api.destroy();

const out = [
  "// Generated by `npm run compile -w zk` from zk/circuit/src/main.nr. Do not edit.",
  `export const circuit = ${JSON.stringify(program)} as const;`,
  `export const verificationKeyBase64 = ${JSON.stringify(Buffer.from(vk).toString("base64"))};`,
  "",
].join("\n");
writeFileSync(`${outDir}/income_to_rent.ts`, out);
console.log(`Compiled: ${program.abi.parameters.length} params, vk ${vk.length} bytes -> zk/artifacts/income_to_rent.ts`);
